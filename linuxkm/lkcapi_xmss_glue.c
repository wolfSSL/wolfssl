/* XMSS/XMSS^MT (RFC 8391, NIST SP 800-208) glue.  VERIFY-ONLY, deliberately:
 * XMSS is a stateful hash-based signature scheme -- each signing operation
 * consumes a one-time-signature key, and reusing one voids all security.  Safe
 * signing therefore requires durable, synchronized private-key state
 * (wc_XmssKey signing requires read/write state callbacks), for which the
 * kernel crypto API has no contract, and mismanaged state in-kernel would be an
 * OTS-reuse hazard.  SP 800-208 confines signing to controlled (hardware)
 * modules; verification has no state.  The sign/set_priv_key callbacks are
 * -EOPNOTSUPP stubs, following the convention of the in-tree ML-DSA
 * implementation (crypto/mldsa.c) for unsupported operations.
 *
 * The kernel has no in-tree XMSS implementation on any version, hence no
 * CONFIG_CRYPTO_XMSS to pivot on for LINUXKM_LKCAPI_REGISTER_ALL_KCONFIG,
 * and no config-conflict check either -- the alg is registered for
 * LINUXKM_LKCAPI_REGISTER_ALL, or by explicit request only.
 *
 * Calling conventions (wolfSSL-defined -- no in-tree or OpenSSL
 * precedent for kernel XMSS):
 *   - two cra_names are registered, "xmss" (single-tree, RFC 8391
 *     section 4) and "xmssmt" (multi-tree, RFC 8391 section 5), which
 *     use disjoint OID spaces distinguished only by that split:
 *     set_pub_key takes the raw public key (OID || root || SEED), from
 *     which the parameter set is derived (using the alg's
 *     single/multi-tree hint) and validated by
 *     wc_XmssKey_ImportPubRaw_ex().
 *   - verify takes the raw XMSS/XMSS^MT signature as src and the raw unhashed
 *     message, of any length, as the "digest" argument.  Signature size
 *     mismatches and verification failures both return -EBADMSG,
 *     following the convention of the in-tree ML-DSA.
 *   - key_size returns the public key size in BYTES on all kernel
 *     versions, and digest_size is not set, both mirroring the in-tree
 *     ML-DSA conventions for the PQC signature family.
 *
 * Because the "xmss"/"xmssmt" cra_names are unknown to crypto/testmgr.c, alg_test()
 * takes its "notest" path and returns success at registration time, with
 * or without fips_enabled.  KATs are instead supplied by
 * linuxkm_test_xmss() below.
 */

