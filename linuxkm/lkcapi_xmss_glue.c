static int km_xmss_init_common(struct xmss_tfm_type *tfm, int is_xmssmt)
{
    struct km_xmss_ctx *ctx = xmss_tfm_ctx_cb(tfm);
    int ret;

#ifndef LINUXKM_LKCAPI_REGISTER_XMSS_MT
    if (is_xmssmt)
        return -EOPNOTSUPP;
#endif

    XMEMSET(ctx, 0, sizeof(struct km_xmss_ctx));
    ctx->is_xmssmt = is_xmssmt;

    ctx->key = (XmssKey *)malloc(sizeof(XmssKey));
    if (! ctx->key)
        return -ENOMEM;

    ret = wc_XmssKey_Init(ctx->key, NULL /* heap */, INVALID_DEVID);
    if (ret < 0) {
        free(ctx->key);
        ctx->key = NULL;
        return -ENOMEM;
    }

    #ifdef WOLFKM_DEBUG_XMSS
    pr_info("info: exiting km_xmss_init_common (xmssmt %d)\n", is_xmssmt);
    #endif
    return 0;
}

static int km_xmss_init(struct xmss_tfm_type *tfm)
{
    return km_xmss_init_common(tfm, 0);
}

#ifdef LINUXKM_LKCAPI_REGISTER_XMSS_MT
static int km_xmssmt_init(struct xmss_tfm_type *tfm)
{
    return km_xmss_init_common(tfm, 1);
}
#endif

static void km_xmss_exit(struct xmss_tfm_type *tfm)
{
    struct km_xmss_ctx *ctx = xmss_tfm_ctx_cb(tfm);

    if (ctx->key) {
        wc_XmssKey_Free(ctx->key);
        free(ctx->key);
        ctx->key = NULL;
    }

    #ifdef WOLFKM_DEBUG_XMSS
    pr_info("info: exiting km_xmss_exit\n");
    #endif
    return;
}

/*
 * Sets the XMSS/XMSS^MT public key.
 *
 * tfm     the crypto_akcipher (crypto_sig on linux 6.13+) transform
 * key     raw RFC 8391 public key (OID || root || SEED); the
 *         parameter set is derived from the OID, using the alg's
 *         single/multi-tree hint, and validated
 * keylen  key length
 */
static int km_xmss_set_pub(struct xmss_tfm_type *tfm, const void *key,
                          unsigned int keylen)
{
    struct km_xmss_ctx * ctx = xmss_tfm_ctx_cb(tfm);
    int                 err;

    if (key == NULL)
        return -EINVAL;

    if (ctx->key == NULL)
        return -EINVAL;

    /* reset the key for (re)import. */
    wc_XmssKey_Free(ctx->key);
    ctx->pub_set = 0;
    err = wc_XmssKey_Init(ctx->key, NULL /* heap */, INVALID_DEVID);
    if (err != 0)
        return -ENOMEM;

    /* Derives and validates the parameter set from the encoded OID
     * (NOT_COMPILED_IN / BAD_FUNC_ARG if the set isn't built in). */
    err = wc_XmssKey_ImportPubRaw_ex(ctx->key, (const byte *)key, keylen,
                                     ctx->is_xmssmt);
    if (unlikely(err)) {
        #ifdef WOLFKM_DEBUG_XMSS
        pr_err("%s: wc_XmssKey_ImportPubRaw_ex failed: %d\n",
               ctx->is_xmssmt ? WOLFKM_XMSSMT_DRIVER : WOLFKM_XMSS_DRIVER,
               err);
        #endif
        return -EINVAL;
    }

    ctx->pub_set = 1;

    #ifdef WOLFKM_DEBUG_XMSS
    pr_info("info: exiting km_xmss_set_pub %d\n", keylen);
    #endif
    return 0;
}

