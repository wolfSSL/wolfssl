/*
 * Verify an XMSS/XMSS^MT signature.
 *
 * The total size of req->src is src_len + dst_len:
 *   - src_len: signature (raw RFC 8391 form, exact size for the
 *     imported public key's parameter set)
 *   - dst_len: message (raw, unhashed, any length up to INT_MAX)
 *
 * dst should be null.
 */
static int km_xmss_verify(struct akcipher_request *req)
{
    struct crypto_akcipher * tfm = NULL;
    struct km_xmss_ctx *      ctx = NULL;
    byte *                   sig = NULL;
    word32                   sig_len = 0;
    byte *                   msg = NULL;
    word32                   msg_len = 0;
    int                      err = -1;

    if (req->src == NULL || req->dst != NULL)
        return -EINVAL;

    tfm = crypto_akcipher_reqtfm(req);
    ctx = akcipher_tfm_ctx(tfm);

    sig_len = req->src_len;
    msg_len = req->dst_len;

    if ((sig_len + msg_len) != ((word64)sig_len + (word64)msg_len))
        return -EINVAL;

    sig = malloc(sig_len + msg_len);
    if (unlikely(sig == NULL))
        return -ENOMEM;

    msg = sig + sig_len;

    XMEMSET(sig, 0, sig_len + msg_len);

    scatterwalk_map_and_copy(sig, req->src, 0, sig_len + msg_len, 0);

    err = km_xmss_verify_common(ctx, sig, sig_len, msg, msg_len);

    free(sig);

    #ifdef WOLFKM_DEBUG_XMSS
    pr_info("info: exiting km_xmss_verify msg_len %d, sig_len %d, "
            "err %d\n", msg_len, sig_len, err);
    #endif
    return err;
}

