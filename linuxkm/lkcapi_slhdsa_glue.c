/* SLH-DSA (FIPS 205) glue, covering all twelve parameter sets, each
 * individually gated on its wolfCrypt WOLFSSL_SLHDSA_PARAM_NO_* /
 * WOLFSSL_SLHDSA_SHA2 configuration.
 *
 * The kernel has no in-tree SLH-DSA implementation on any version (the
 * only in-tree PQC signature is ML-DSA, crypto/mldsa.c), hence no
 * CONFIG_CRYPTO_SLHDSA to pivot on for
 * LINUXKM_LKCAPI_REGISTER_ALL_KCONFIG, and no config-conflict check
 * either -- the algs are registered for LINUXKM_LKCAPI_REGISTER_ALL, or
 * by explicit request only.
 *
 * Calling conventions (wolfSSL-defined; the out-of-tree leancrypto
 * kernel module registers SLH-DSA sigver with the same
 * signature-then-message akcipher src convention):
 *   - cra_names are the FIPS 205 parameter set names, lowercased:
 *     "slh-dsa-shake-128s" ... "slh-dsa-sha2-256f".
 *   - set_pub_key takes the raw public key (PK.seed || PK.root, 2*n
 *     bytes exactly); set_priv_key takes the raw FIPS 205 private key
 *     (SK.seed || SK.prf || PK.seed || PK.root, 4*n bytes exactly),
 *     which contains the public key, so set_priv_key also installs the
 *     public half (matching the in-tree ML-DSA, where set_pub is
 *     likewise optional after set_priv).
 *   - verify takes the raw signature as src and the raw unhashed
 *     message as the "digest" argument: the pure SLH-DSA.Verify of
 *     FIPS 205 algorithm 24, with an empty context string.  Signature
 *     size mismatches and verification failures both return -EBADMSG.
 *   - sign is the hedged (randomized) pure SLH-DSA.Sign of FIPS 205
 *     algorithm 22, with an empty context string, per the FIPS 205
 *     section 9.2 default; -EOVERFLOW on insufficient dst, per the
 *     kernel's rsassa-pkcs1 convention.
 *   - key_size returns the public key size in BYTES on all kernel
 *     versions, and digest_size is not set, both mirroring the in-tree
 *     ML-DSA conventions for the PQC signature family.
 *
 * Because these cra_names are unknown to crypto/testmgr.c, alg_test()
 * takes its "notest" path and returns success at registration time,
 * with or without fips_enabled.  Self-tests are instead supplied by
 * the linuxkm_test_slhdsa_*() functions below, which test the LKCAPI
 * plumbing; algorithm-correctness KATs live in wolfcrypt/test/test.c's
 * slhdsa_test(), which is built into the module whenever
 * LINUXKM_LKCAPI_REGISTER is (see the self-test comment below).
 */

