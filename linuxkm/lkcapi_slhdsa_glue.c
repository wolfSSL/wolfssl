static int linuxkm_test_slhdsa_driver(const char * driver, int param)
{
    int                       test_rc = WC_NO_ERR_TRACE(WC_FAILURE);
    int                       ret = 0;
    struct crypto_akcipher *  tfm = NULL;
    struct akcipher_request * req = NULL;
    struct scatterlist        src_tab[2];
    struct scatterlist        dst_sg;
    byte                      pub[WOLFKM_SLHDSA_MAX_PUB_LEN];
    byte                      priv[WOLFKM_SLHDSA_MAX_PRIV_LEN];
    const byte *              kat_sig = NULL;
    byte *                    work = NULL;
    byte *                    sig_buf = NULL;
    byte *                    msg_buf = NULL;
    byte *                    out_buf = NULL;
    word32                    pub_len;
    word32                    priv_len;
    word32                    sig_len;
    const word32              msg_len = (word32)sizeof(slhdsa_test_msg);

    {
        int len = wc_SlhDsaKey_PublicSizeFromParam((enum SlhDsaParam)param);
        if (len <= 0) {
            test_rc = BAD_FUNC_ARG;
            goto test_slhdsa_end;
        }
        pub_len = (word32)len;
        len = wc_SlhDsaKey_SigSizeFromParam((enum SlhDsaParam)param);
        if (len <= 0) {
            test_rc = BAD_FUNC_ARG;
            goto test_slhdsa_end;
        }
        sig_len = (word32)len;
#ifdef LINUXKM_SLHDSA_SIGN
        len = wc_SlhDsaKey_PrivateSizeFromParam((enum SlhDsaParam)param);
        if (len <= 0) {
            test_rc = BAD_FUNC_ARG;
            goto test_slhdsa_end;
        }
        priv_len = (word32)len;
#else
        priv_len = 0;
#endif
    }

    ret = linuxkm_test_slhdsa_get_vectors(param, pub, pub_len, priv,
                                          priv_len, &kat_sig);
    if (ret != 0) {
        pr_err("error: slhdsa test vector setup failed: %d\n", ret);
        test_rc = ret;
        goto test_slhdsa_end;
    }

    /* one allocation: mutable signature + message + sign output. */
    work = (byte *)malloc((2 * (size_t)sig_len) + msg_len);
    if (! work) {
        pr_err("error: allocating work buffer failed.\n");
        test_rc = MEMORY_E;
        goto test_slhdsa_end;
    }
    sig_buf = work;
    msg_buf = work + sig_len;
    out_buf = work + sig_len + msg_len;
    XMEMSET(sig_buf, 0xa5, sig_len);
    if (kat_sig)
        XMEMCPY(sig_buf, kat_sig, sig_len);
    XMEMCPY(msg_buf, slhdsa_test_msg, msg_len);

    tfm = crypto_alloc_akcipher(driver, 0, 0);
    if (IS_ERR(tfm)) {
        pr_err("error: allocating akcipher algorithm %s failed: %d\n",
               driver, (int)PTR_ERR(tfm));
        if (PTR_ERR(tfm) == -ENOMEM)
            test_rc = MEMORY_E;
        else
            test_rc = BAD_FUNC_ARG;
        tfm = NULL;
        goto test_slhdsa_end;
    }

    req = akcipher_request_alloc(tfm, GFP_KERNEL);
    if (! req) {
        test_rc = -ENOMEM;
        pr_err("error: allocating akcipher request %s failed\n",
               driver);
        goto test_slhdsa_end;
    }

    ret = crypto_akcipher_set_pub_key(tfm, pub, pub_len);
    if (ret) {
        pr_err("error: crypto_akcipher_set_pub_key returned: %d\n", ret);
        test_rc = BAD_FUNC_ARG;
        goto test_slhdsa_end;
    }

    {
        unsigned int maxsize = crypto_akcipher_maxsize(tfm);
        if (maxsize != sig_len) {
            pr_err("error: crypto_akcipher_maxsize returned %u, "
                   "expected %u\n", maxsize, sig_len);
            test_rc = BAD_FUNC_ARG;
            goto test_slhdsa_end;
        }
    }

#ifdef LINUXKM_SLHDSA_SIGN
    ret = crypto_akcipher_set_priv_key(tfm, priv, priv_len);
    if (ret) {
        pr_err("error: crypto_akcipher_set_priv_key returned: %d\n",
               ret);
        test_rc = BAD_FUNC_ARG;
        goto test_slhdsa_end;
    }

    /* hedged signing is nondeterministic -- test by roundtrip. */
    sg_init_one(&src_tab[0], msg_buf, msg_len);
    sg_init_one(&dst_sg, out_buf, sig_len);
    akcipher_request_set_crypt(req, &src_tab[0], &dst_sg, msg_len,
                               sig_len);

    ret = crypto_akcipher_sign(req);
    if (ret) {
        pr_err("error: crypto_akcipher_sign returned: %d\n", ret);
        test_rc = BAD_FUNC_ARG;
        goto test_slhdsa_end;
    }
    if (req->dst_len != sig_len) {
        pr_err("error: crypto_akcipher_sign set dst_len %u, expected "
               "%u\n", req->dst_len, sig_len);
        test_rc = BAD_FUNC_ARG;
        goto test_slhdsa_end;
    }

    XMEMCPY(sig_buf, out_buf, sig_len);

    sg_init_table(src_tab, 2);
    sg_set_buf(&src_tab[0], sig_buf, sig_len);
    sg_set_buf(&src_tab[1], msg_buf, msg_len);
    akcipher_request_set_crypt(req, src_tab, NULL, sig_len, msg_len);

    ret = crypto_akcipher_verify(req);
    if (ret) {
        pr_err("error: crypto_akcipher_verify of generated signature "
               "returned: %d\n", ret);
        test_rc = BAD_FUNC_ARG;
        goto test_slhdsa_end;
    }

    /* insufficient dst space must fail with -EOVERFLOW. */
    sg_init_one(&src_tab[0], msg_buf, msg_len);
    sg_init_one(&dst_sg, out_buf, sig_len - 1);
    akcipher_request_set_crypt(req, &src_tab[0], &dst_sg, msg_len,
                               sig_len - 1);
    ret = crypto_akcipher_sign(req);
    if (ret != -EOVERFLOW) {
        pr_err("error: crypto_akcipher_sign (short dst) returned %d, "
               "expected %d\n", ret, -EOVERFLOW);
        test_rc = BAD_FUNC_ARG;
        goto test_slhdsa_end;
    }
#else /* !LINUXKM_SLHDSA_SIGN */
    if (kat_sig) {
        /* embedded accept-path KAT. */
        sg_init_table(src_tab, 2);
        sg_set_buf(&src_tab[0], sig_buf, sig_len);
        sg_set_buf(&src_tab[1], msg_buf, msg_len);
        akcipher_request_set_crypt(req, src_tab, NULL, sig_len, msg_len);

        ret = crypto_akcipher_verify(req);
        if (ret) {
            pr_err("error: crypto_akcipher_verify returned: %d\n", ret);
            test_rc = BAD_FUNC_ARG;
            goto test_slhdsa_end;
        }
    }

    /* sign-side stubs must report -EOPNOTSUPP. */
    ret = crypto_akcipher_set_priv_key(tfm, pub, pub_len);
    if (ret != -EOPNOTSUPP) {
        pr_err("error: crypto_akcipher_set_priv_key returned %d, "
               "expected %d\n", ret, -EOPNOTSUPP);
        test_rc = BAD_FUNC_ARG;
        goto test_slhdsa_end;
    }
    sg_init_one(&src_tab[0], msg_buf, msg_len);
    sg_init_one(&dst_sg, out_buf, sig_len);
    akcipher_request_set_crypt(req, &src_tab[0], &dst_sg, msg_len,
                               sig_len);
    ret = crypto_akcipher_sign(req);
    if (ret != -EOPNOTSUPP) {
        pr_err("error: crypto_akcipher_sign returned %d, expected %d\n",
               ret, -EOPNOTSUPP);
        test_rc = BAD_FUNC_ARG;
        goto test_slhdsa_end;
    }
#endif /* !LINUXKM_SLHDSA_SIGN */

    /* reject path: corrupt (or garbage) signature of correct length
     * must fail with -EBADMSG. */
    sig_buf[sig_len / 2] ^= 1U;
    sg_init_table(src_tab, 2);
    sg_set_buf(&src_tab[0], sig_buf, sig_len);
    sg_set_buf(&src_tab[1], msg_buf, msg_len);
    akcipher_request_set_crypt(req, src_tab, NULL, sig_len, msg_len);

    ret = crypto_akcipher_verify(req);
    if (ret != -EBADMSG) {
        pr_err("error: crypto_akcipher_verify returned %d, expected "
               "%d\n", ret, -EBADMSG);
        test_rc = BAD_FUNC_ARG;
        goto test_slhdsa_end;
    }

    test_rc = 0;
test_slhdsa_end:
    if (req) { akcipher_request_free(req); req = NULL; }
    if (tfm) { crypto_free_akcipher(tfm); tfm = NULL; }
    if (work) { free(work); work = NULL; }
#ifdef LINUXKM_SLHDSA_SIGN
    ForceZero(priv, sizeof(priv));
#endif

    #ifdef WOLFKM_DEBUG_SLHDSA
    pr_info("info: %s: self test returned: %d\n", driver, test_rc);
    #endif
    return test_rc;
}

