int test_wolfSSL_DSA_up_ref(void)
{
    EXPECT_DECLS;
#if !defined(HAVE_SELFTEST) && !defined(HAVE_FIPS) && \
    !defined(WC_FIPS_186_5_PLUS) && defined(OPENSSL_EXTRA) && \
    !defined(NO_FILESYSTEM) && !defined(NO_DSA)
    DSA* dsa = NULL;
    DSA_SIG* sig = NULL;
    unsigned char digest[WC_SHA_DIGEST_SIZE];
    byte der[TWOK_BUF];
    int derSz = 0;
    XFILE fp = XBADFILE;

    ExpectIntEQ(DSA_up_ref(NULL), 0);

    XMEMSET(digest, 0x5a, sizeof(digest));
    ExpectTrue((fp = XFOPEN("./certs/dsa2048.der", "rb")) != XBADFILE);
    ExpectIntGT(derSz = (int)XFREAD(der, 1, sizeof(der), fp), 0);
    if (fp != XBADFILE)
        XFCLOSE(fp);
    ExpectNotNull(dsa = DSA_new());
    ExpectIntEQ(DSA_LoadDer(dsa, der, derSz), 1);
    ExpectIntEQ(DSA_up_ref(dsa), 1);
    if (EXPECT_SUCCESS()) {
        /* Releases the reference taken above. The key stays usable. */
        DSA_free(dsa);
    }
    ExpectNotNull(sig = DSA_do_sign(digest, (int)sizeof(digest), dsa));
    ExpectIntEQ(DSA_do_verify(digest, (int)sizeof(digest), sig, dsa), 1);
    DSA_SIG_free(sig);
    DSA_free(dsa);
#endif
    return EXPECT_RESULT();
}
