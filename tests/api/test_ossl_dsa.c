int test_wolfSSL_DSA_do_sign_digest_len(void)
{
    EXPECT_DECLS;
#if !defined(HAVE_SELFTEST) && !defined(HAVE_FIPS) && \
    !defined(WC_FIPS_186_5_PLUS) && defined(OPENSSL_EXTRA) && \
    !defined(NO_FILESYSTEM) && !defined(NO_DSA)
    /* OpenSSL signature of the digest below with certs/dsa2048.der. */
    static const unsigned char sigDer[] = {
        0x30, 0x2d, 0x02, 0x14, 0x47, 0xba, 0xa2, 0xa0, 0x80, 0xec, 0xd5, 0xd3,
        0xd4, 0x17, 0xa5, 0xa4, 0xc8, 0xc4, 0xe9, 0x6a, 0xfd, 0x56, 0x37, 0xf4,
        0x02, 0x15, 0x00, 0x86, 0x7f, 0xa1, 0x9c, 0x1e, 0x7b, 0xcc, 0x8b, 0xfa,
        0xb3, 0xc8, 0x47, 0xd8, 0x55, 0xc8, 0x86, 0x31, 0xe1, 0xc7, 0x74
    };
    const unsigned char* p = sigDer;
    unsigned char digest[WC_SHA256_DIGEST_SIZE];
    DSA* dsa = NULL;
    DSA_SIG* sig = NULL;
    byte der[TWOK_BUF];
    int derSz = 0;
    XFILE fp = XBADFILE;

    XMEMSET(digest, 0x5a, sizeof(digest));
    ExpectTrue((fp = XFOPEN("./certs/dsa2048.der", "rb")) != XBADFILE);
    ExpectIntGT(derSz = (int)XFREAD(der, 1, sizeof(der), fp), 0);
    if (fp != XBADFILE)
        XFCLOSE(fp);
    ExpectNotNull(dsa = DSA_new());
    ExpectIntEQ(DSA_LoadDer(dsa, der, derSz), 1);

    /* q is 160 bits: only the leftmost 20 bytes of the digest are used. */
    ExpectNotNull(sig = d2i_DSA_SIG(NULL, &p, (long)sizeof(sigDer)));
    ExpectIntEQ(DSA_do_verify(digest, (int)sizeof(digest), sig, dsa), 1);
    ExpectIntEQ(DSA_do_verify(digest, WC_SHA_DIGEST_SIZE, sig, dsa), 1);
    DSA_SIG_free(sig);
    sig = NULL;

    ExpectNotNull(sig = DSA_do_sign(digest, (int)sizeof(digest), dsa));
    ExpectIntEQ(DSA_do_verify(digest, WC_SHA_DIGEST_SIZE, sig, dsa), 1);
    DSA_SIG_free(sig);
    DSA_free(dsa);
#endif
    return EXPECT_RESULT();
}

