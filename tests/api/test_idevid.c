/* Write tag, length and len bytes of in (header only if in is NULL). */
static int idevid_tlv(byte* out, byte tag, const byte* in, int len)
{
    int i = 0;

    out[i++] = tag;
    if (len >= 0x100) {
        out[i++] = 0x82;
        out[i++] = (byte)(len >> 8);
    }
    else if (len >= 0x80) {
        out[i++] = 0x81;
    }
    out[i++] = (byte)len;
    if (in == NULL)
        return i;
    XMEMCPY(out + i, in, (size_t)len);
    return i + len;
}

/* SAN with count HardwareModuleNames, then an optional dNSName. extraElem 1
 * adds an INTEGER inside the SEQUENCE, 2 adds it after the SEQUENCE. */
static int idevid_hmn_san(byte* out, byte serialTag, const byte* serial,
    int serialSz, int extraElem, int count, int withDns)
{
    static const byte hwType[] = {
        0x06, 0x09, 0x2B, 0x06, 0x01, 0x04, 0x01, 0x86, 0x8D, 0x1F, 0x01
    };
    static const byte hmnOid[] = {
        0x06, 0x08, 0x2B, 0x06, 0x01, 0x05, 0x05, 0x07, 0x08, 0x04
    };
    static const byte extra[] = { 0x02, 0x01, 0x05 };
    static const byte dns[] = {
        0x82, 0x0F, 'd', 'e', 'v', '.', 'e', 'x', 'a', 'm', 'p', 'l', 'e',
        '.', 'c', 'o', 'm'
    };
    byte a[512];
    byte b[512];
    int aSz;
    int bSz;
    int sz;
    int i;

    XMEMCPY(a, hwType, sizeof(hwType));
    aSz = (int)sizeof(hwType);
    aSz += idevid_tlv(a + aSz, serialTag, serial, serialSz);
    if (extraElem == 1) {
        XMEMCPY(a + aSz, extra, sizeof(extra));
        aSz += (int)sizeof(extra);
    }
    bSz = idevid_tlv(b, ASN_SEQUENCE | ASN_CONSTRUCTED, a, aSz);
    if (extraElem == 2) {
        XMEMCPY(b + bSz, extra, sizeof(extra));
        bSz += (int)sizeof(extra);
    }
    XMEMCPY(a, hmnOid, sizeof(hmnOid));
    aSz = (int)sizeof(hmnOid);
    aSz += idevid_tlv(a + aSz, ASN_CONTEXT_SPECIFIC | ASN_CONSTRUCTED, b, bSz);
    bSz = idevid_tlv(b, ASN_CONTEXT_SPECIFIC | ASN_CONSTRUCTED, a, aSz);

    sz = idevid_tlv(out, ASN_SEQUENCE | ASN_CONSTRUCTED, NULL,
        bSz * count + (withDns ? (int)sizeof(dns) : 0));
    for (i = 0; i < count; i++) {
        XMEMCPY(out + sz, b, (size_t)bSz);
        sz += bSz;
    }
    if (withDns) {
        XMEMCPY(out + sz, dns, sizeof(dns));
        sz += (int)sizeof(dns);
    }
    return sz;
}
