        serialSz = (int)sizeof(serial);
        ExpectNotNull(wolfSSL_X509_get_device_type(x509, serial, &serialSz));
        ExpectIntEQ(serialSz, (int)sizeof(longPolicy) - 6);
        ExpectBufEQ(serial, longPolicyOid, sizeof(longPolicy) - 6);
        wolfSSL_X509_free(x509);
        x509 = NULL;
