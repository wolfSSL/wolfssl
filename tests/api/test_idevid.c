/* Make a self-signed cert with the given raw SAN and parse it back. */
static int idevid_parse_san(const byte* san, int sanSz, DecodedCert* dc,
    byte* der, int derMax, int* derSzOut)
{
    Cert* cert = NULL;
    ecc_key key;
    WC_RNG rng;
    int derSz = 0;
    int ret;

    XMEMSET(&key, 0, sizeof(key));
    XMEMSET(&rng, 0, sizeof(rng));
    ret = wc_InitRng(&rng);
    if (ret == 0)
        ret = idevid_load_ecc_key(IDEVID_DIR "dev-key.pem", &key);
    if (ret == 0) {
        cert = (Cert*)XMALLOC(sizeof(Cert), NULL, DYNAMIC_TYPE_TMP_BUFFER);
        if (cert == NULL)
            ret = MEMORY_E;
    }
    if (ret == 0)
        ret = wc_InitCert(cert);
    if (ret == 0) {
        cert->sigType = CTC_SHA256wECDSA;
        XSTRNCPY(cert->subject.serialDev, "SN-0001", CTC_NAME_SIZE);
        XMEMCPY(cert->altNames, san, (size_t)sanSz);
        cert->altNamesSz = sanSz;
    #if defined(WOLFSSL_ASN_TEMPLATE) && defined(WOLFSSL_CUSTOM_OID) && \
        defined(HAVE_OID_ENCODING) && defined(WOLFSSL_CERT_EXT)
        if (idevidExt != NULL) {
            ret = wc_SetCustomExtension(cert, 0, "2.5.29.32", idevidExt,
                idevidExtSz);
        }
    #endif
    }
    if ((ret == 0) && (cert != NULL)) {
        ret = wc_MakeCert(cert, der, (word32)derMax, NULL, &key, &rng);
        if (ret > 0) {
            ret = wc_SignCert(cert->bodySz, cert->sigType, der,
                (word32)derMax, NULL, &key, &rng);
        }
    }
    if (ret > 0) {
        derSz = ret;
        if (derSzOut != NULL)
            *derSzOut = derSz;
        wc_InitDecodedCert(dc, der, (word32)derSz, NULL);
        ret = wc_ParseCert(dc, CERT_TYPE, NO_VERIFY, NULL);
    }
    XFREE(cert, NULL, DYNAMIC_TYPE_TMP_BUFFER);
    wc_ecc_free(&key);
    wc_FreeRng(&rng);
    return ret;
}
