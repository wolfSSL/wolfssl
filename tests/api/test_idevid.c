#define IDEVID_DIR "./certs/idevid/"

#if defined(IDEVID_TEST_DEPS) && !defined(NO_FILESYSTEM) && \
    defined(IDEVID_CM_VERIFY)
static int idevid_cm_verify(const char* inter, const char* leaf)
{
    WOLFSSL_CERT_MANAGER* cm;
    int ret = WC_NO_ERR_TRACE(WOLFSSL_FATAL_ERROR);

    cm = wolfSSL_CertManagerNew();
    if (cm == NULL)
        return ret;
    ret = wolfSSL_CertManagerLoadCA(cm, IDEVID_DIR "root-cert.pem", NULL);
    if (ret == WOLFSSL_SUCCESS)
        ret = wolfSSL_CertManagerLoadCA(cm, inter, NULL);
    if (ret == WOLFSSL_SUCCESS)
        ret = wolfSSL_CertManagerVerify(cm, leaf, WOLFSSL_FILETYPE_ASN1);
    wolfSSL_CertManagerFree(cm);
    return ret;
}
#endif

int test_idevid_cm_verify(void)
{
    EXPECT_DECLS;
#if defined(IDEVID_TEST_DEPS) && !defined(NO_FILESYSTEM) && \
    defined(IDEVID_CM_VERIFY)
    const char* inter = IDEVID_DIR "int-cert.pem";
    const char* interNc = IDEVID_DIR "int-nc-cert.pem";

    ExpectIntEQ(idevid_cm_verify(inter, IDEVID_DIR "dev-ecc-cert.der"),
        WOLFSSL_SUCCESS);
    ExpectIntEQ(idevid_cm_verify(inter, IDEVID_DIR "dev-ecc-nocn-cert.der"),
        WOLFSSL_SUCCESS);
    ExpectIntEQ(idevid_cm_verify(inter, IDEVID_DIR "dev-ecc-dns-cert.der"),
        WOLFSSL_SUCCESS);
    ExpectIntEQ(idevid_cm_verify(inter, IDEVID_DIR "dev-ecc-eku-cert.der"),
        WOLFSSL_SUCCESS);
#ifndef NO_RSA
    ExpectIntEQ(idevid_cm_verify(inter, IDEVID_DIR "dev-rsa-cert.der"),
        WOLFSSL_SUCCESS);
#endif
#if !defined(IGNORE_NAME_CONSTRAINTS) && (!defined(WOLFSSL_X509_TINY) || \
    defined(WOLFSSL_X509_TINY_NAME_CONSTRAINTS))
    /* A dNSName constraint does not restrict an otherName-only SAN. */
    ExpectIntEQ(idevid_cm_verify(interNc, IDEVID_DIR "dev-ecc-nc-cert.der"),
        WOLFSSL_SUCCESS);
    ExpectIntEQ(idevid_cm_verify(interNc,
        IDEVID_DIR "dev-ecc-nc-dns-cert.der"), WOLFSSL_SUCCESS);
#else
    (void)interNc;
#endif
    ExpectIntEQ(idevid_cm_verify(inter,
        IDEVID_DIR "dev-ecc-masacrit-cert.der"),
        WC_NO_ERR_TRACE(ASN_CRIT_EXT_E));
#endif
    return EXPECT_RESULT();
}

#if defined(IDEVID_TEST_DEPS) && !defined(NO_ASN_TIME) && \
    ((defined(IDEVID_CM_VERIFY) && !defined(NO_ASN_TIME_CHECK)) || \
     defined(HAVE_SSL_MEMIO_TESTS_DEPENDENCIES))
static time_t idevidNow;
static time_t idevid_time_cb(time_t* t)
{
    if (t != NULL)
        *t = idevidNow;
    return idevidNow;
}
#endif

#if defined(IDEVID_TEST_DEPS) && !defined(NO_ASN_TIME) && \
    !defined(NO_FILESYSTEM) && defined(IDEVID_CM_VERIFY) && \
    !defined(NO_ASN_TIME_CHECK)
/* MSVC's gmtime stops at the year 3000. */
static int idevid_gmtime_ok(time_t t)
{
    struct tm tmpTime;
    struct tm* ret;

    XMEMSET(&tmpTime, 0, sizeof(tmpTime));
    ret = (struct tm*)XGMTIME(&t, &tmpTime);
    return (ret != NULL);
}

static int idevid_cm_verify_at(time_t now)
{
    WOLFSSL_CERT_MANAGER* cm;
    int ret = WC_NO_ERR_TRACE(WOLFSSL_FATAL_ERROR);

    cm = wolfSSL_CertManagerNew();
    if (cm == NULL)
        return ret;
    ret = wolfSSL_CertManagerLoadCA(cm, IDEVID_DIR "root-cert.pem", NULL);
    if (ret == WOLFSSL_SUCCESS)
        ret = wolfSSL_CertManagerLoadCA(cm, IDEVID_DIR "int-cert.pem", NULL);
    if (ret == WOLFSSL_SUCCESS) {
        idevidNow = now;
        wc_SetTimeCb(idevid_time_cb);
        ret = wolfSSL_CertManagerVerify(cm, IDEVID_DIR "dev-ecc-cert.der",
            WOLFSSL_FILETYPE_ASN1);
        wc_SetTimeCb(NULL);
    }
    wolfSSL_CertManagerFree(cm);
    return ret;
}
#endif

int test_idevid_date_limits(void)
{
    EXPECT_DECLS;
#if defined(IDEVID_TEST_DEPS) && !defined(NO_ASN_TIME)
    static const byte gt9999[] = {
        0x18, 0x0F, '9', '9', '9', '9', '1', '2', '3', '1', '2', '3', '5',
        '9', '5', '9', 'Z'
    };
    const byte* date = NULL;
    byte format = 0;
    int length = 0;
    struct tm tm;

    XMEMSET(&tm, 0, sizeof(tm));
    ExpectIntEQ(wc_GetDateInfo(gt9999, (int)sizeof(gt9999), &date, &format,
        &length), 0);
    ExpectIntEQ(format, ASN_GENERALIZED_TIME);
    ExpectIntEQ(wc_GetDateAsCalendarTime(date, length, format, &tm), 0);
    ExpectIntEQ(tm.tm_year + 1900, 9999);
    ExpectIntEQ(tm.tm_mon, 11);
    ExpectIntEQ(tm.tm_mday, 31);

#if !defined(NO_FILESYSTEM) && defined(IDEVID_CM_VERIFY) && \
    !defined(NO_ASN_TIME_CHECK)
    /* Device clock unset fails the notBefore check. */
    ExpectIntEQ(idevid_cm_verify_at((time_t)86400),
        WC_NO_ERR_TRACE(ASN_BEFORE_DATE_E));
    ExpectIntEQ(idevid_cm_verify_at((time_t)0x7FFFFFF0), WOLFSSL_SUCCESS);
    /* 9999-12-31T23:46:40Z, then 10000-01-01T00:00:00Z. */
    if ((sizeof(time_t) > 4) && idevid_gmtime_ok((time_t)253402300000LL)) {
        ExpectIntEQ(idevid_cm_verify_at((time_t)253402300000LL),
            WOLFSSL_SUCCESS);
    }
    if ((sizeof(time_t) > 4) && idevid_gmtime_ok((time_t)253402300800LL)) {
        ExpectIntEQ(idevid_cm_verify_at((time_t)253402300800LL),
            WC_NO_ERR_TRACE(ASN_AFTER_DATE_E));
    }
#endif
#endif
    return EXPECT_RESULT();
}

#if defined(IDEVID_TEST_DEPS) && defined(HAVE_SSL_MEMIO_TESTS_DEPENDENCIES) && \
    !defined(NO_ASN_TIME) && !defined(NO_FILESYSTEM) && !defined(NO_CERTS) && \
    !defined(NO_TLS) && !defined(NO_WOLFSSL_CLIENT) && \
    !defined(NO_WOLFSSL_SERVER)
#define IDEVID_TLS_SETUP_FAILED (-2)
static int idevidAcceptBefore;
static int idevid_verify_cb(int preverify, WOLFSSL_X509_STORE_CTX* store)
{
    int notYetValid = (store->error == WC_NO_ERR_TRACE(ASN_BEFORE_DATE_E));

#if defined(OPENSSL_EXTRA) || defined(OPENSSL_EXTRA_X509_SMALL)
    /* OPENSSL_COMPATIBLE_DEFAULTS reports the mapped X509_V_ERR code. */
    if (store->error == WOLFSSL_X509_V_ERR_CERT_NOT_YET_VALID)
        notYetValid = 1;
#endif
    if (!preverify && idevidAcceptBefore && notYetValid)
        return 1;
    return preverify;
}

static int idevid_tls(const char* chain, int chainType, const char* key,
    const char* extraCa, time_t serverNow, int acceptBefore)
{
    EXPECT_DECLS;
    WOLFSSL_CTX *ctx_c = NULL, *ctx_s = NULL;
    WOLFSSL *ssl_c = NULL, *ssl_s = NULL;
    struct test_memio_ctx test_ctx;
    int ret;

    XMEMSET(&test_ctx, 0, sizeof(test_ctx));
    ExpectNotNull(ctx_c = wolfSSL_CTX_new(wolfSSLv23_client_method()));
    ExpectNotNull(ctx_s = wolfSSL_CTX_new(wolfSSLv23_server_method()));
    wolfSSL_CTX_set_verify(ctx_c, WOLFSSL_VERIFY_NONE, NULL);
    if (chainType == WOLFSSL_FILETYPE_ASN1) {
        ExpectIntEQ(wolfSSL_CTX_use_certificate_file(ctx_c, chain,
            WOLFSSL_FILETYPE_ASN1), WOLFSSL_SUCCESS);
    }
    else {
        ExpectIntEQ(wolfSSL_CTX_use_certificate_chain_file(ctx_c, chain),
            WOLFSSL_SUCCESS);
    }
    ExpectIntEQ(wolfSSL_CTX_use_PrivateKey_file(ctx_c, key,
        WOLFSSL_FILETYPE_PEM), WOLFSSL_SUCCESS);
    ExpectIntEQ(wolfSSL_CTX_use_certificate_file(ctx_s, svrCertFile,
        WOLFSSL_FILETYPE_PEM), WOLFSSL_SUCCESS);
    ExpectIntEQ(wolfSSL_CTX_use_PrivateKey_file(ctx_s, svrKeyFile,
        WOLFSSL_FILETYPE_PEM), WOLFSSL_SUCCESS);
    ExpectIntEQ(wolfSSL_CTX_load_verify_locations(ctx_s,
        IDEVID_DIR "root-cert.pem", NULL), WOLFSSL_SUCCESS);
    if (extraCa != NULL) {
        ExpectIntEQ(wolfSSL_CTX_load_verify_locations(ctx_s, extraCa, NULL),
            WOLFSSL_SUCCESS);
    }
    idevidAcceptBefore = acceptBefore;
    wolfSSL_CTX_set_verify(ctx_s, WOLFSSL_VERIFY_PEER |
        WOLFSSL_VERIFY_FAIL_IF_NO_PEER_CERT, idevid_verify_cb);
    wolfSSL_SetIORecv(ctx_c, test_memio_read_cb);
    wolfSSL_SetIOSend(ctx_c, test_memio_write_cb);
    wolfSSL_SetIORecv(ctx_s, test_memio_read_cb);
    wolfSSL_SetIOSend(ctx_s, test_memio_write_cb);
    ExpectIntEQ(test_memio_setup(&test_ctx, &ctx_c, &ctx_s, &ssl_c, &ssl_s,
        wolfSSLv23_client_method, wolfSSLv23_server_method), 0);

    if (serverNow != 0) {
        idevidNow = serverNow;
        wc_SetTimeCb(idevid_time_cb);
    }
    ret = test_memio_do_handshake(ssl_c, ssl_s, 10, NULL);
    wc_SetTimeCb(NULL);
    if (ret != 0) {
        ret = wolfSSL_get_error(ssl_s, WOLFSSL_FATAL_ERROR);
        if (ret == 0)
            ret = WOLFSSL_FATAL_ERROR;
    }

    wolfSSL_free(ssl_c);
    wolfSSL_free(ssl_s);
    wolfSSL_CTX_free(ctx_c);
    wolfSSL_CTX_free(ctx_s);
    if (!EXPECT_SUCCESS())
        return IDEVID_TLS_SETUP_FAILED;
    return ret;
}
#endif

