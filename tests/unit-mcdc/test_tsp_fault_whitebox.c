/*
 * MC/DC fault/argument-guard white-box supplement for wolfcrypt/src/tsp.c.
 *
 * tests/api/test_tsp.c and tests/unit-mcdc/test_tsp_whitebox.c together drive
 * the module's happy paths and most static-helper argument guards. The
 * campaign's GAPS.md still lists a residual set of MC/DC independence pairs
 * as unshown in the union of all variant runs; this file targets those,
 * providing BOTH rows of each pair in this one binary (MC/DC independence is
 * computed per binary, not merged across separately-compiled #include
 * copies of tsp.c - see mcdc_fault_alloc.h and the other tests/unit-mcdc
 * fault whiteboxes for the same rule).
 *
 * Two techniques not used elsewhere in the tsp.c white-boxes:
 *
 *  1. XGMTIME mock: wc_TspTstInfo_SetGenTimeAsTime()'s
 *     `(ts == NULL) || ValidateGmtime(ts)` guard (tsp.c:797) can only see
 *     ts==NULL or an invalid struct tm when the platform's real gmtime()
 *     fails or returns something ValidateGmtime rejects - not reliably
 *     triggerable with real clock values. wc_port.h's XGMTIME macro is only
 *     defined `#if !defined(XGMTIME)`, so defining it here BEFORE
 *     #include <wolfcrypt/src/tsp.c> installs a controllable replacement for
 *     tsp.c's own (only) use of it, without touching any other translation
 *     unit (every other file's XGMTIME expansion is fixed at that file's own
 *     compile time in the already-built library). wbXGMTIME() passes through
 *     to the real gmtime() by default and switches to returning NULL, an
 *     out-of-range struct tm, or a struct tm with a huge tm_year (ValidateGmtime
 *     does not range-check tm_year) on request - the last of these also drives
 *     the `(n < 0) || (n >= (int)bufSz)` truncation guard at tsp.c:808.
 *
 *  2. Hand-built X.509 certificates: Tsp_CheckSignerCert()'s extended-key-usage
 *     (tsp.c:1763) and key-usage (tsp.c:1773) guards need certificates with
 *     properties no existing certs_test.h fixture has - no EKU extension at
 *     all, an EKU that is present but not critical, and a KeyUsage extension
 *     present but with no recognized bit set. These are generated once
 *     (openssl req -x509, self-signed) and embedded as DER byte arrays below;
 *     ParseCertRelative() is called by Tsp_CheckSignerCert() with NO_VERIFY,
 *     so an invalidated signature (the KU-zero cert has its KeyUsage bit
 *     string patched to all-zero bits AFTER signing, to get a KeyUsage
 *     extension with literally no bit set) does not matter - only the
 *     extension structure is under test. See the generation notes at each
 *     array.
 *
 * Real signed CMS token: TspResponse_Verify()'s post-verify decisions
 * (cm != NULL at tsp.c:2162, and the tstInfo/contentSz rows at tsp.c:2179/
 * 2188 it shares the same successful-verify prerequisite with) need a
 * genuinely valid signed CMS SignedData TimeStampToken to reach ret == 0 at
 * that point - documented in test_tsp_whitebox.c as not attempted there.
 * wb_make_token() builds one the same way tests/api/test_tsp.c's
 * test_tsp_make_token() does: wc_TspTstInfo_SignWithPkcs7() with
 * tsa_cert_der_2048/tsa_key_der_2048 (real RSA signature over real
 * SignedAttributes).
 *
 * DEATHNOTE claim check (asn_tsp.c:1433, condition index 0,
 * `GetASNTag(signers, &idx, &tag, signersSz) < 0`, inside
 * TspCheckOneSignerInfo()'s `while ((ret == 0) && (idx < signersSz))` loop):
 * CONFIRMED dead at this call site. GetASNTag() only fails when
 * `idx + ASN_TAG_SZ > maxIdx` (asn.c, ASN_TAG_SZ == 1); the enclosing loop
 * guard `idx < signersSz` already guarantees `idx + 1 <= signersSz` on every
 * entry to the loop body, and idx is not advanced between the guard and the
 * call, so `idx + ASN_TAG_SZ > signersSz` can never hold here.
 *
 * asn_tsp.c is #include'd into asn.c (not its own translation unit); this
 * file only needs its WOLFSSL_LOCAL declarations, already linked into the
 * built library's asn.o - no #include of asn_tsp.c is attempted here (see
 * test_tsp_whitebox.c's header for why that would be unnecessary anyway:
 * none of the residuals here are in one of its file-static helpers).
 *
 * Targeted residuals, by GAPS.md line (17 NULL/argument-guard conditions):
 *   tsp.c:797  idx0,idx1   - SetGenTimeAsTime ts==NULL / ValidateGmtime
 *   tsp.c:1033 idx3,idx5   - SetFromRequest policySz==0 / serialSz==0
 *   tsp.c:1175 idx4        - CheckRequest nonce content mismatch
 *   tsp.c:1182 idx3        - CheckRequest policy size mismatch
 *   tsp.c:1472 idx2        - SignWithPkcs7 singleCertSz==0
 *   tsp.c:1683 idx0,idx2   - Tsp_CheckTsaName subjectRaw==NULL / mismatch
 *   tsp.c:1697 idx0,idx2   - Tsp_CheckTsaName rfc822Name / uri tag
 *   tsp.c:1763 idx0,idx3   - Tsp_CheckSignerCert no-EKU / EKU-not-critical
 *   tsp.c:1773 idx0,idx2   - Tsp_CheckSignerCert no-KU / KU-zero-bits
 *   tsp.c:2162 idx0,idx1   - TspResponse_Verify cm != NULL
 * Plus allocation err-chain coverage (mcdc_fault_alloc.h fault sweep) over
 * wc_TspTstInfo_SignWithPkcs7()'s tstDer/attribs XMALLOC calls, and two cheap
 * bonus rows opportunistic with the above (tsp.c:939 SetNonce loop entry,
 * and the 2179/2188 tstInfo!=NULL/contentSz>0 rows that fall out of the real
 * token used for 2162).
 *
 * Documented as NOT attempted (out of this pass's scope):
 *   - tsp.c:808 idx0 (XSNPRINTF returning negative): no legitimate input
 *     drives this on a real libc snprintf; not claimed dead, just unreached.
 *   - tsp.c:1112/1854, 2167:3, 2179 idx2 true row (contentSz==0),
 *     2188/2230, and every asn_tsp.c-only decode-side item in GAPS.md
 *     (341/354/362/369/557/714/718/1021/1194/1343/1429/1445): each needs
 *     either a clock/libc fault this file's XGMTIME mock does not reach, a
 *     zero-length-content token this pass did not construct, or DER
 *     surgery on an encoded TSTInfo/TimeStampResp whose exact byte offsets
 *     were not worked out here - same class of residual test_tsp_whitebox.c
 *     already documents.
 */

#include <time.h>
