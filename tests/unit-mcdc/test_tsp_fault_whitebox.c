/* ---- XGMTIME mock: installed before tsp.c is compiled - see file header
 * technique (1). Mode is a plain int, not an enum, so tsp.c's own headers
 * (included by the #include below) cannot collide with a symbol name. ---- */
static int wbGmtimeMode = 0; /* 0 passthrough, 1 NULL, 2 invalid tm, 3 huge year */
static struct tm wbFakeTm;

static struct tm* wbXGMTIME(const time_t* clock, struct tm* tmpBuf)
{
    (void)tmpBuf;
    if (wbGmtimeMode == 1) {
        /* 797 idx0 true: XGMTIME "fails". */
        return NULL;
    }
    if (wbGmtimeMode == 2) {
        /* 797 idx1 true: a struct tm ValidateGmtime rejects (tm_mday==0 and
         * tm_hour==99 both out of its accepted ranges). */
        memset(&wbFakeTm, 0, sizeof(wbFakeTm));
        wbFakeTm.tm_hour = 99;
        return &wbFakeTm;
    }
    if (wbGmtimeMode == 3) {
        /* 797 false, 808 idx1 true: a real, ValidateGmtime-valid tm, but
         * with tm_year pushed huge (ValidateGmtime does not range-check
         * tm_year) so the formatted GeneralizedTime string overflows bufSz. */
        struct tm* real = gmtime(clock);
        if (real == NULL) {
            return NULL;
        }
        wbFakeTm = *real;
        wbFakeTm.tm_year = 99999999;
        return &wbFakeTm;
    }
    /* Passthrough: real gmtime(), same as the default (non-reentrant) tail
     * of wc_port.h's own XGMTIME chain - single-threaded test, safe. */
    return gmtime(clock);
}
#define XGMTIME(c, t) wbXGMTIME((c), (t))

